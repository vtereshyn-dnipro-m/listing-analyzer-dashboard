# -*- coding: utf-8 -*-
"""
services/translate.py — перевод текстовых слоёв макета.

Перевод здесь не «текст на входе, текст на выходе». Три вещи делают
его особенным, и все три живут в промпте.

ПРЕДЕЛ. У каждой строки своя ширина слоя в макете, и немецкий длиннее
английского примерно на пятую часть. Модель обязана знать предел
КАЖДОЙ строки, иначе перевод придётся переписывать после экспорта.

СЛОВАРЬ. Дизайнер уже перевёл часть карточек, и там сложился свой
язык: «Akku-Tacker», а не «Batterie-Hefter». Готовые пары идут
в промпт образцом — не чтобы модель их повторила, а чтобы попадала
в тот же словарь.

ВИДИМОСТЬ. Промпт показывается человеку целиком и правится им же.
Скрытый промпт — это чужие решения, которые невозможно оспорить:
дизайнер видит «не переводить название модели» и добавляет своё
правило туда же, а не пишет о нём в чат.

Промпт хранится в `synthesis_skill` со `scope = 'translate'`, как
и остальные методологии: версии, откат в один клик, правка без
коммитов. Текст по умолчанию ниже — он ВИДЕН на экране до первого
сохранения и помечен как несохранённый, поэтому подмены, из-за
которой мы потеряли методологию тайтлов, здесь произойти не может:
человек читает ровно то, что уйдёт модели.
"""
from __future__ import annotations

import json
import re

SCOPE = "translate"
TASK = "translate"

# Языки целей — человеческими именами для промпта
LANG_NAME = {
    "de": "немецкий", "es": "испанский",
    "it": "итальянский", "fr": "французский",
}

DEFAULT_PROMPT = """\
Ты переводишь тексты с карточек товара Amazon для бренда Dnipro-M.
Это инструменты: аккумуляторные пилы, шуруповёрты, воздуходувки.

Правила:

1. Названия моделей не переводятся и не меняются: CC-36, DCS-200,
   TJF-36, DVB-200. Пишутся ровно так, как в исходнике.
2. Числа, единицы и их формат не трогаются: «1,500 mAh», «3.6 V»,
   «30 shots/min» переносятся как есть, кроме случая, когда единица
   называется словом.
3. Бренд Dnipro-M остаётся латиницей.
4. Заголовок остаётся заголовком: короткая фраза без точки в конце.
   Подпись под ним — обычное предложение.
5. Тон — как у инструкции к инструменту: спокойно и по делу, без
   рекламных превосходных степеней.
6. Предел символов у каждой строки обязателен к соблюдению. Если
   точный перевод не влезает, сокращай формулировку, а не смысл:
   выбрасывай вводные слова, а не факты.
"""


# Строки, которые не переводятся: числа с единицами и коды моделей.
# Проверено по живым макетам — 44 из 153 английских строк дизайнер
# не тронул ни на одном языке: «2 Ah», «11–13 min», «240 km/h»,
# «BP-220», «BP-240/240N».
#
# ВАЖНО, где проходит граница. «Capacity» и «Speed I» выглядят такими
# же служебными, но в макетах они ПЕРЕВЕДЕНЫ: «Capacidad», «Capacità»,
# «Velocidad I». Поэтому решают признаки, а не список слов: слово
# остаётся словом и уходит в перевод.
# Единицы перечислены СПИСКОМ, а не «любые буквы после числа».
# Разница видна на живом примере: «30 shots/min» в макетах переведено
# как «30 Schuss/min» и «30 colpi/min» — единица тут СЛОВО, и оно
# переводится. Проглоти правило любые буквы, мы бы молча потеряли
# такие строки, а это как раз оговорка из промпта по умолчанию:
# «кроме случая, когда единица называется словом».
UNITS = (r"mAh|Ah|mA|kWh|Wh|kW|W|V|Hz|kg|g|mm|cm|m|km|h|min|s|ms|"
         r"m³/h|m3/h|m/s|km/h|rpm|bar|Nm|L|ml|°C|°F|%")
NUM_UNIT = re.compile(
    rf"^[\d.,]+(?:\s*[–—-]\s*[\d.,]+)?"           # 2 · 11–13
    rf"(?:\s*(?:{UNITS}))?"                          # Ah · km/h · m³/h
    rf"(?:\s+[\d.,]+\s*(?:{UNITS}))*$")             # 19 min 45 s
MODEL_CODE = re.compile(r"^[A-Z]{1,4}[- ]?\d{1,4}[A-Z]*(?:/\d{1,4}[A-Z]*)?$")


def is_boilerplate(text: str) -> bool:
    """Строку переводить не нужно: число, единица или код модели.

    Такие строки одинаковы на всех языках, и отправлять их в модель —
    это платить за подтверждение того, что «2 Ah» это «2 Ah». Из 153
    строк первого захода таких 44, то есть почти треть таблицы: без
    отсева они превращают экран в шум, в котором теряется работа.
    """
    s = str(text or "").strip()
    if not s:
        return True
    return bool(NUM_UNIT.match(s) or MODEL_CODE.match(s))


def split_rows(rows: list) -> tuple[list, list]:
    """(что переводим, что не требует перевода) — в порядке исходника."""
    work, skip = [], []
    for r in rows:
        (skip if is_boilerplate(r.get("source_text")) else work).append(r)
    return work, skip


def build_prompt(prompt_text: str, lang: str, rows: list, pairs: list) -> str:
    """Готовый текст запроса к модели: правила, словарь, строки.

    Собирается ОДНОЙ строкой и целиком показывается человеку — это
    и есть то, что уйдёт модели, без скрытых добавок.
    """
    name = LANG_NAME.get(lang, lang)
    parts = [prompt_text.strip(), "", f"Язык перевода: {name}."]

    if pairs:
        parts += ["", "Уже переведённые строки этого проекта — держись "
                      "того же словаря и тона:"]
        for p in pairs:
            parts.append(f"  {p['en']}  →  {p['tr']}")

    parts += ["", "Переведи строки ниже. У каждой указан предел символов: "
                  "перевод длиннее предела в макет не влезет.",
              "Ответь ТОЛЬКО массивом JSON вида "
              '[{"slot": "...", "text": "..."}] без пояснений.', ""]
    for r in rows:
        limit = r.get("char_limit")
        cap = f"не больше {int(limit)} знаков" if limit else "предел неизвестен"
        parts.append(f'  slot={r["slot"]}  ({cap})  {r["source_text"]}')
    return "\n".join(parts)


def run(prompt_text: str, lang: str, rows: list, pairs: list) -> tuple[dict, str]:
    """Перевод строк моделью: ({slot: текст}, имя модели).

    Модель зовётся тем же слоем, что и остальные задачи, — провайдер
    выбирается в Настройках. Пустой ответ здесь не «перевод пустой»,
    а «не получилось»: ошибка уже показана слоем вызова, и записывать
    поверх работы человека нечего.
    """
    from services import ai                     # локально: тесты без сети
    provider, model = ai.task_config(TASK)
    reply = ai.generate_json(
        TASK, build_prompt(prompt_text, lang, rows, pairs))
    return parse_reply(reply), model


def parse_reply(raw) -> dict:
    """Ответ модели → {slot: перевод}. Мусор молча не проглатывается."""
    if isinstance(raw, str):
        try:
            raw = json.loads(raw)
        except ValueError:
            return {}
    if isinstance(raw, dict):
        raw = raw.get("translations") or raw.get("items") or []
    out = {}
    for item in raw or []:
        if isinstance(item, dict) and item.get("slot"):
            text = item.get("text")
            if isinstance(text, str) and text.strip():
                out[str(item["slot"])] = text.strip()
    return out
