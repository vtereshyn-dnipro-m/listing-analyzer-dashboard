-- Назначение роли пилота «Генератор текстов» человеку. 21.10.2026.
--
-- ВЫПОЛНЯЕТСЯ В БАЗЕ КАБИНЕТА, от роли Кабинета (она владеет app_users), —
-- владельцем, вручную. Агент Listing Suite к базе Кабинета не подключается и этот
-- файл не выполняет.
--
-- Решение владельца 21.10.2026: «Роль пилота — позже Алексею, почту не подставляй».
-- Поэтому назначение вынесено из 2026-10-21_ls_textgen_role.sql: роль и права
-- заводятся сейчас, а человеку роль даётся этим файлом, когда его подключат.
--
-- Порядок: после 2026-10-21_ls_textgen_role.sql (без него CHECK не знает роль).
--
-- Почта — подставить перед выполнением. Пока стоит заготовка, блок отказывается
-- выполняться и откатывает всю транзакцию. Строки в app_users нет — блок тоже
-- отказывается: пусть человек один раз войдёт с рабочей почты (вход заводит
-- карточку «Просмотр» сам), и файл выполняется после этого. Заводить карточку
-- здесь значило бы молча решать и про доступ в Кабинет.
-- Кабинетную роль (`role`) блок не трогает.
BEGIN;

DO $$
DECLARE
    почта text := 'ПОДСТАВИТЬ_ПОЧТУ';
    n int;
BEGIN
    IF почта = 'ПОДСТАВИТЬ_ПОЧТУ' THEN
        RAISE EXCEPTION 'Почта не подставлена — роль никому не назначена';
    END IF;
    UPDATE kabinet_data.app_users SET ls_role = 'textgen_pilot'
     WHERE lower(email) = lower(почта);
    GET DIAGNOSTICS n = ROW_COUNT;
    IF n <> 1 THEN
        RAISE EXCEPTION 'Строк с почтой %: % (нужна ровно одна)', почта, n;
    END IF;
END $$;

COMMIT;

-- Проверка: у кого роль пилота.
SELECT email, ls_role FROM kabinet_data.app_users WHERE ls_role = 'textgen_pilot';
