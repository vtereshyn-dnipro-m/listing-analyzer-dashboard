-- Узлы макета на каждый язык: чтобы показывать НАСТОЯЩУЮ карточку.
--
-- Часть товаров уже переведена в самой Figma — Мария делала руками,
-- и на языковых страницах лежат готовые макеты с переведённым текстом
-- прямо на картинке. Показывать рядом с ними английский рендер значит
-- прятать готовую работу: дизайнер сверяет строки с макетом, которого
-- в этом языке давно нет.
--
-- Проверено по файлу на 10.09.2026: языковых макетов одиннадцать —
-- у пяти товаров на ES и IT, у одного (B0G4S9SJ3M) на DE.
--
-- Почему jsonb, а не таблица и не колонки по языкам. Языков сейчас
-- четыре, завтра шесть; колонка на язык означала бы миграцию на каждый
-- новый рынок. Отдельная таблица под «ASIN → язык → узел» — это связь
-- один-к-одному с товаром, ради которой пришлось бы держать join
-- в каждом чтении списка.
--
-- Узел здесь — ФРЕЙМ `.MAIN`, то есть главное изображение. В слоях
-- (`figma_layers`) его нет и быть не может: текста в `.MAIN` нет ни
-- у одного товара из двадцати одного, поэтому обход текстовых слоёв
-- его не видит.

BEGIN;

ALTER TABLE listing_data.figma_products
    ADD COLUMN IF NOT EXISTS lang_nodes jsonb NOT NULL DEFAULT '{}'::jsonb;

COMMENT ON COLUMN listing_data.figma_products.lang_nodes IS
    'Узлы .MAIN по языкам: {"de": "1482:33161", "it": "1482:41531"}. '
    'Английский лежит отдельно в figma_node_id — он есть всегда.';

COMMIT;
