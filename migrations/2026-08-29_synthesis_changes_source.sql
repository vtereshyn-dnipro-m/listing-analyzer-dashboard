-- listing_data.synthesis_changes: откуда взялся принятый текст
--
-- Зачем. До сих пор в таблице лежало только «что приняли» и «какой моделью
-- сделан черновик». После появления кнопки «Редактировать» этого мало:
-- принятый текст может быть и тем, что выдала модель, и тем, что человек
-- переписал руками поверх черновика. Различать их нужно по двум причинам.
--
-- Первая — честность плашки. Поле model говорит, чем СГЕНЕРИРОВАН черновик,
-- и остаётся верным даже после ручной правки. Без отдельного признака
-- карточка утверждала бы, что тайтл написала модель, хотя его переписал
-- человек.
--
-- Вторая — оценка методологии. Доля ручных правок это и есть мера того,
-- насколько методология попадает: если её правят руками в половине случаев,
-- чинить надо методологию, а не тайтлы по одному. Посчитать это можно
-- только при разделённых источниках.
--
-- Значения: 'ai' — принято как сгенерировано, 'manual' — принято после
-- ручной правки. DEFAULT 'ai' делает миграцию безопасной для уже
-- накопленных строк: они действительно приняты без ручного вмешательства.
--
-- Применяет Databricks. Приложение схему не создаёт и не меняет.

ALTER TABLE listing_data.synthesis_changes
    ADD COLUMN IF NOT EXISTS source TEXT NOT NULL DEFAULT 'ai';

-- разрез «сколько правим руками» по рынку и времени
CREATE INDEX IF NOT EXISTS idx_synthesis_changes_source
    ON listing_data.synthesis_changes (source, marketplace, accepted_at DESC);
