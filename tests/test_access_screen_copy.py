# -*- coding: utf-8 -*-
"""
tests/test_access_screen_copy.py — экран «Доступ» здесь ВЫКЛАДКА, а не вторая версия.

`access_screen.py` — один на два приложения, и его источник лежит в репозитории
Кабинета. Здесь копия, и она обязана совпадать с источником байт в байт: две версии
одной админки разошлись бы молча, а таблицы у них общие — поведение разное при тех же
данных.

Проверить «совпадает ли с источником» отсюда нельзя: чужого репозитория на Streamlit
Cloud нет. Но можно поймать ПРАВКУ КОПИИ НА МЕСТЕ — именно так расхождение и начинается.
В первой строке файла лежит sha256 его собственного содержимого, который поставил
скрипт выкладки; правка на месте этот отпечаток ломает.

Сверку двух репозиториев делает `scratchpad/sync_access_screen.py --проверить` в
Кабинете — она видит обе стороны.

Запуск (pytest не нужен):  python tests/test_access_screen_copy.py
"""
from __future__ import annotations

import hashlib
import os
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ФАЙЛ = ROOT / "access_screen.py"
FAILS: list[str] = []


def check(name: str, cond: bool) -> None:
    print(("  OK   " if cond else "  FAIL ") + name)
    if not cond:
        FAILS.append(name)


check("выкладка на месте", ФАЙЛ.exists())
if ФАЙЛ.exists():
    текст = ФАЙЛ.read_text(encoding="utf-8")
    м = re.match(r"# ОТПЕЧАТОК ИСТОЧНИКА: ([0-9a-f]{64})\n", текст)
    check("в шапке есть отпечаток источника", bool(м))
    if м:
        тело = текст[м.end():]
        посчитан = hashlib.sha256(тело.encode("utf-8")).hexdigest()
        check(f"отпечаток совпадает с содержимым ({посчитан[:12]}…)",
              посчитан == м.group(1))
    # Обёртка обязана звать общий модуль, а не повторять его: страница без вызова
    # `render` означала бы, что экран живёт здесь своей жизнью.
    обёртка = (ROOT / "pages" / "access.py").read_text(encoding="utf-8")
    check("страница зовёт общий модуль", "access_screen.render(" in обёртка)
    check("и не содержит своей разметки экрана",
          "st.tabs(" not in обёртка and "data_editor" not in обёртка)

    # Жёсткое `require("admin")` в общем модуле — молчаливый отказ на каждом
    # сохранении у второго продукта: такого действия в его матрице нет вовсе, экран
    # открылся бы, а кнопки отказывали. Право берётся то же, которым открыт экран.
    check("экран не зовёт кабинетное право строкой",
          'require("admin"' not in текст and 'can("admin"' not in текст)
    check("и держит запертые пары на оба продукта",
          '"ls.admin"' in текст and "ЗАПЕРТО" in текст)

# --- сверка с ИСТОЧНИКОМ, если репозиторий Кабинета под рукой
# Расхождение — провал, а не предупреждение (решение владельца 02.10.2026).
# Источника нет рядом — это не расхождение, и провалом не считается: правку копии на
# месте уже поймал отпечаток выше, а полная сверка живёт там, где лежит источник, и
# стоит в его обязательном прогоне (`scratchpad/smoke_full.py` Кабинета).
ИСТОЧНИК = pathlib.Path(os.environ.get(
    "KABINET_ROOT", "/Users/vitter/Documents/Code/kabinet-dashboard")) / "access_screen.py"
if ИСТОЧНИК.exists():
    check("копия совпадает с источником побайтно",
          ИСТОЧНИК.read_bytes() == ФАЙЛ.read_bytes())
else:
    print(f"  —    источника рядом нет ({ИСТОЧНИК}); полная сверка — в прогоне Кабинета")

print()
print("ИТОГ:", "все проверки прошли" if not FAILS
      else f"{len(FAILS)} провалов: {FAILS}")
sys.exit(1 if FAILS else 0)
